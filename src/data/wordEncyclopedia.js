/**
 * Search the encyclopedia by keyword (word, definition, synonyms, grade)
 */
export function searchEncyclopedia(query, gradeFilter = null) {
  const cleanQ = (query || '').trim().toLowerCase();
  return WORD_ENCYCLOPEDIA.filter((item) => {
    if (gradeFilter && gradeFilter !== 'all' && String(item.grade) !== String(gradeFilter)) {
      return false;
    }
    if (!cleanQ) return true;
    const haystack = [
      item.word,
      item.kidDefinition,
      item.officialDefinition || '',
      item.subject,
      item.partOfSpeech,
      ...(item.synonyms || []),
      ...(item.antonyms || [])
    ].join(' ').toLowerCase();
    return haystack.includes(cleanQ);
  });
}
